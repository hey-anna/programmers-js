// 공 던지기

// 원형으로 서 있는 친구들 중
// 한 번 던질 때마다 한 명을 건너뛰고 다음 사람에게 공을 던진다.
// 즉, 공은 2칸씩 이동한다.

// k번째로 공을 던지는 사람의 위치를 구하기 위해
// (k - 1)번 이동한 칸 수를 계산한다.
// 한 번 던질 때마다 2칸 이동하므로
// 총 이동 칸 수는 (k - 1) * 2 이다.

// 원형 구조이므로 배열 길이를 넘어가면
// 나머지 연산(%)으로 다시 처음으로 돌아간다.

const solution = (numbers, k) => {
  const index = ((k - 1) * 2) % numbers.length;
  const result = numbers[index];
  return result;
};
